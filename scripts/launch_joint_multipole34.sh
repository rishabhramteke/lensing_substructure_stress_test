#!/bin/zsh
# Joint scan with FREE m=3 and m=4 terms (referee round 19): the cost of azimuthal freedom in both orders. Same
# subsamples as launch_joint_multipole.sh. Then the c-M template on a c-M-drawn population (mass bias for the
# realistic pairing) and an intermediate depth (600 s) for the joint scan, once those populations exist. Resumable.
#   caffeinate -i zsh scripts/launch_joint_multipole34.sh
source /Users/rishabh.ramteke/myenv/bin/activate
cd /Users/rishabh.ramteke/Documents/space_research/projects/05_dark_matter_strong_lensing
export OMP_NUM_THREADS=1 MKL_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 VECLIB_MAXIMUM_THREADS=1
W=${WORKERS:-6}
run() {  # run <population> <n> <n_subsample> <seed> <concentration> <out> [extra args]
  pop=$1; n=$2; nsub=$3; seed=$4; conc=$5; out=$6; shift 6
  if [ -f $out/manifest.json ]; then echo "skip $out (done)"; return; fi
  mkdir -p $(dirname $out); echo "=== $out  $(date)"
  python scripts/run_baseline_a_joint.py --population $pop --n $n --n-subsample $nsub --seed $seed --concentration $conc \
      --workers $W --out $out "$@" > $out.log 2>&1
}
R=results/baseline_a_joint_mp34
run no_subhalo      300 300 1 15 $R/no_subhalo      --macro-multipole --macro-multipole-orders 3,4
run multipole_m3_a3 300 300 3 15 $R/multipole_m3_a3 --macro-multipole --macro-multipole-orders 3,4
run test_fixed60    300 300 0 15 $R/test_fixed60    --macro-multipole --macro-multipole-orders 3,4
run multipole_m4_a3 300 300 3 15 $R/multipole_m4_a3 --macro-multipole --macro-multipole-orders 3,4
# c-M template on the c-M-drawn population (generated by launch_gen_round19.sh; same seed as test_fixed60)
while [ ! -f data/test_cdm/manifest.json ]; do sleep 60; done
run test_cdm 300 300 0 cm results/baseline_a_joint_cm/test_cdm
# intermediate depth, 600 s: clean control and c=60, 200 lenses each
for pop in test_shallow600_no_subhalo test_shallow600_fixed60; do while [ ! -f data/$pop/manifest.json ]; do sleep 60; done; done
run test_shallow600_no_subhalo 200 300 1 15 results/baseline_a_joint_shallow600/no_subhalo
run test_shallow600_fixed60    200 300 0 15 results/baseline_a_joint_shallow600/test_fixed60
echo "ALL DONE $(date)"
