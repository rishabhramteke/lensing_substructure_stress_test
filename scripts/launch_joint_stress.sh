#!/bin/zsh
# Joint Family A scan on the stress populations, on the SAME lens subsamples as the frozen scans
# (same --seed), in order of importance. Resumable.
#   caffeinate -i zsh scripts/launch_joint_stress.sh
source /Users/rishabh.ramteke/myenv/bin/activate
cd /Users/rishabh.ramteke/Documents/space_research/projects/05_dark_matter_strong_lensing
export OMP_NUM_THREADS=1 MKL_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 VECLIB_MAXIMUM_THREADS=1
W=${WORKERS:-4}
run() {  # run <population> <n> <n_subsample> <seed> <out> [extra args]
  pop=$1; n=$2; nsub=$3; seed=$4; out=$5; shift 5
  if [ -f $out/manifest.json ]; then echo "skip $out (done)"; return; fi
  mkdir -p $(dirname $out)
  echo "=== $out  $(date)"
  python scripts/run_baseline_a_joint.py --population $pop --n $n --n-subsample $nsub --seed $seed --concentration 15 \
      --workers $W --out $out "$@" > $out.log 2>&1
}
# line-of-sight halos (frozen: results/baseline_a_los, seed 5)
run los_halo_z025 300 300 5 results/baseline_a_joint_los/los_z025
run los_halo_z075 300 300 5 results/baseline_a_joint_los/los_z075
# survey depth (frozen: results/baseline_a_shallow, seeds 1/0/0/3)
run test_shallow_no_subhalo     300 300 1 results/baseline_a_joint_shallow/no_subhalo
run test_shallow_fixed60        300 300 0 results/baseline_a_joint_shallow/test_fixed60
run test_shallow_fixed15        300 300 0 results/baseline_a_joint_shallow/test_fixed15
run test_shallow_multipole_m4_a3 300 300 3 results/baseline_a_joint_shallow/multipole_m4_a3
# non-physical decoys at the brightest amplitude (populations of 100; frozen numbers in results/noise_decoy_control*)
run decoy_gaussian_s42_a10 100 100 0 results/baseline_a_joint_decoy/decoy_gaussian_s42_a10
run decoy_gaussian_s43_a10 100 100 0 results/baseline_a_joint_decoy/decoy_gaussian_s43_a10
run decoy_dipole_s42_a10   100 100 0 results/baseline_a_joint_decoy/decoy_dipole_s42_a10
# PSF widened to 0.15" (populations generated by launch_psf.sh; frozen numbers alongside)
run psf015_no_subhalo 200 300 1 results/baseline_a_joint_psf015/no_subhalo
run psf015_fixed60    200 300 0 results/baseline_a_joint_psf015/test_fixed60
# lens light, first seed set, single (under-flexible) and double (correct) Sersic
run lenslight_no_subhalo       200 300 1 results/baseline_a_joint_lenslight/lenslight_no_subhalo       --lens-light-components 1
run lenslight_fixed60          200 300 0 results/baseline_a_joint_lenslight/lenslight_fixed60          --lens-light-components 1
run lenslight_multipole_m4_a3  200 300 3 results/baseline_a_joint_lenslight/lenslight_multipole_m4_a3  --lens-light-components 1
run lenslight_no_subhalo       200 300 1 results/baseline_a_joint_lenslight2/lenslight_no_subhalo      --lens-light-components 2
run lenslight_fixed60          200 300 0 results/baseline_a_joint_lenslight2/lenslight_fixed60         --lens-light-components 2
run lenslight_multipole_m4_a3  200 300 3 results/baseline_a_joint_lenslight2/lenslight_multipole_m4_a3 --lens-light-components 2
# tidal track (Appendix A; frozen: results/baseline_a_tidal, seed 0)
run test_tidal_c15 200 300 0 results/baseline_a_joint_tidal/test_tidal_c15
run test_tidal_c30 200 300 0 results/baseline_a_joint_tidal/test_tidal_c30
echo "ALL DONE $(date)"
